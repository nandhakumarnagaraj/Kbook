CREATE TABLE IF NOT EXISTS restaurant_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL,
    plan_code VARCHAR(50) NOT NULL REFERENCES subscription_plans(code),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    billing_cycle VARCHAR(20) NOT NULL DEFAULT 'MONTHLY',
    started_at BIGINT NOT NULL,
    current_period_start BIGINT NOT NULL,
    current_period_end BIGINT NOT NULL,
    trial_end_at BIGINT,
    grace_period_end_at BIGINT,
    auto_renew BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_restaurant_subscriptions_restaurant UNIQUE (restaurant_id)
);

CREATE INDEX IF NOT EXISTS idx_restaurant_subscriptions_status
    ON restaurant_subscriptions (status);
CREATE INDEX IF NOT EXISTS idx_restaurant_subscriptions_period_end
    ON restaurant_subscriptions (current_period_end);

-- Backfill all existing active restaurants into PRO tier with 1 year complimentary subscription
INSERT INTO restaurant_subscriptions (
    restaurant_id, plan_code, status, billing_cycle,
    started_at, current_period_start, current_period_end,
    trial_end_at, grace_period_end_at, auto_renew, notes,
    created_at, updated_at, version
)
SELECT
    rp.restaurant_id,
    'PRO' AS plan_code,
    'ACTIVE' AS status,
    'YEARLY' AS billing_cycle,
    COALESCE(rp.created_at, CAST(EXTRACT(EPOCH FROM NOW()) * 1000 AS BIGINT)) AS started_at,
    CAST(EXTRACT(EPOCH FROM NOW()) * 1000 AS BIGINT) AS current_period_start,
    CAST(EXTRACT(EPOCH FROM (NOW() + INTERVAL '1 year')) * 1000 AS BIGINT) AS current_period_end,
    NULL AS trial_end_at,
    NULL AS grace_period_end_at,
    TRUE AS auto_renew,
    'Grandfathered complimentary subscription for existing merchant' AS notes,
    CAST(EXTRACT(EPOCH FROM NOW()) * 1000 AS BIGINT) AS created_at,
    CAST(EXTRACT(EPOCH FROM NOW()) * 1000 AS BIGINT) AS updated_at,
    0 AS version
FROM restaurantprofiles rp
ON CONFLICT (restaurant_id) DO NOTHING;
