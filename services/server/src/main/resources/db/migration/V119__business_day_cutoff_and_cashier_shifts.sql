-- Business-day cutoff, cashier shifts, and the durable closing-report outbox.
--
-- Design: docs/planning/BUSINESS_DAY_CUTOFF_AND_SHIFTS_PLAN_2026-11-06.md
--
-- Two deliberate non-changes:
--   * bills gets NO new date column. The business date is already
--     bills.last_reset_date (VARCHAR(50) NOT NULL, V1:168); V97 exists to correct it.
--     A second column would be a second source of truth for one fact.
--   * ux_bills_restaurant_terminal_daily_active (V26:101) is NOT rebuilt. It already
--     keys on last_reset_date and serves report queries by prefix.
--
-- Safe to deploy before any client change: a 00:00 cutoff plus a NULL effective instant
-- is bit-identical to the previous calendar-day rule.

-- 1. Business-day configuration on the restaurant profile.
ALTER TABLE restaurantprofiles
    ADD COLUMN IF NOT EXISTS opening_time TIME NOT NULL DEFAULT '08:00:00',
    ADD COLUMN IF NOT EXISTS closing_time TIME NOT NULL DEFAULT '23:00:00',
    ADD COLUMN IF NOT EXISTS business_day_cutoff_time TIME NOT NULL DEFAULT '00:00:00',
    ADD COLUMN IF NOT EXISTS cutoff_effective_from BIGINT,
    ADD COLUMN IF NOT EXISTS email_daily_closing_report BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS daily_closing_email_recipients TEXT;

COMMENT ON COLUMN restaurantprofiles.business_day_cutoff_time IS
    'Local time at which the business day rolls. 00:00 keeps the legacy calendar-day rule.';
COMMENT ON COLUMN restaurantprofiles.cutoff_effective_from IS
    'Epoch ms from which the cutoff rule applies; NULL = never. Forward-only: bills '
    'created before this instant keep the calendar rule, so no stored business date is '
    'rewritten and no printed order number changes.';

-- 2. Per-terminal capability gate. The cutoff may only be activated once every active
--    terminal runs a build that understands it; an old client computes calendar days and
--    would have its printed numbers renumbered by the server's duplicate repair.
ALTER TABLE restaurant_terminal
    ADD COLUMN IF NOT EXISTS cutoff_capable BOOLEAN NOT NULL DEFAULT FALSE;

-- 3. Cashier shifts: device-authored (offline-first), server-sealed, append-only once
--    CLOSED. Append-only matters: last-write-wins must never reopen a closed drawer.
CREATE TABLE IF NOT EXISTS cashier_shifts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id            BIGINT        NOT NULL,
    device_id           VARCHAR(255)  NOT NULL,
    restaurant_id       BIGINT        NOT NULL,
    terminal_id         VARCHAR(255)  NOT NULL,
    terminal_series     VARCHAR(255),
    cashier_user_id     BIGINT,
    cashier_name        VARCHAR(255),
    business_date       DATE          NOT NULL,
    opened_at           BIGINT        NOT NULL,
    closed_at           BIGINT,
    opening_float       NUMERIC(12,2) NOT NULL DEFAULT 0,
    declared_cash       NUMERIC(12,2),
    expected_cash       NUMERIC(12,2),
    cash_variance       NUMERIC(12,2),
    total_revenue       NUMERIC(12,2),
    total_orders        INT,
    status              VARCHAR(30)   NOT NULL DEFAULT 'ACTIVE',
    close_source        VARCHAR(30),
    snapshot_json       TEXT,
    public_token        UUID          NOT NULL DEFAULT gen_random_uuid(),
    created_at          BIGINT,
    updated_at          BIGINT,
    server_updated_at   BIGINT,
    is_deleted          BOOLEAN       NOT NULL DEFAULT FALSE,
    version             BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_cashier_shifts_device_local UNIQUE (restaurant_id, device_id, local_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_cashier_shifts_public_token
    ON cashier_shifts (public_token);
CREATE UNIQUE INDEX IF NOT EXISTS ux_cashier_shifts_one_active_per_terminal
    ON cashier_shifts (restaurant_id, terminal_id)
    WHERE status = 'ACTIVE' AND is_deleted = false;
CREATE INDEX IF NOT EXISTS idx_cashier_shifts_restaurant_date
    ON cashier_shifts (restaurant_id, business_date);

-- 4. Transactional email outbox. Same shape as webhook_retry_job, which already runs a
--    PENDING/DEAD_LETTER worker with exponential backoff and admin replay.
--    `revision` is part of the key so a late offline shift can re-send a corrected EOD
--    instead of being blocked by a unique constraint.
CREATE TABLE IF NOT EXISTS email_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id   BIGINT       NOT NULL,
    report_type     VARCHAR(50)  NOT NULL,   -- SHIFT_CLOSE | DAILY_EOD
    reference_key   VARCHAR(255) NOT NULL,   -- shift public_token | business date
    revision        INT          NOT NULL DEFAULT 1,
    recipient       TEXT         NOT NULL,
    subject         TEXT         NOT NULL,
    html_body       TEXT         NOT NULL,
    status          VARCHAR(30)  NOT NULL DEFAULT 'PENDING',
    attempt_count   INT          NOT NULL DEFAULT 0,
    max_attempts    INT          NOT NULL DEFAULT 5,
    next_attempt_at BIGINT,
    last_error      TEXT,
    created_at      BIGINT       NOT NULL,
    updated_at      BIGINT       NOT NULL,
    sent_at         BIGINT,
    CONSTRAINT uq_email_outbox_revision
        UNIQUE (report_type, reference_key, revision, recipient)
);

CREATE INDEX IF NOT EXISTS idx_email_outbox_pending
    ON email_outbox (status, next_attempt_at)
    WHERE status IN ('PENDING', 'FAILED');
